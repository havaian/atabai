import { Injectable } from '@nestjs/common';
import { InjectModel } from '@nestjs/mongoose';
import * as fs from 'fs';
import * as path from 'path';
import { Types } from 'mongoose';

import { AppLoggerService } from '../../common/logger/app-logger.service';
import {
  ALL_ACCOUNT_VIDS,
  type AccountVid,
  isAccountVid,
} from '../constants/account-vid';
import {
  ChartOfAccount,
  type ChartOfAccountModel,
} from '../schemas/chart-of-account.schema';

// __dirname resolves to src/ledger/services/ in dev (ts-node) and
// dist/ledger/services/ in prod — both layouts carry the seed JSON one level
// up under seedChart/ thanks to copy-assets.mjs.
const SEED_DIR = path.join(__dirname, '..', 'seedChart');
const SEED_FILE = 'nsbu-chart-of-accounts.json';

interface SeedAccount {
  code: string;
  name: string;
  subconto1Name: string | null;
  subconto2Name: string | null;
  subconto3Name: string | null;
  vid: AccountVid;
  isCurrencyTracked: boolean;
  isQuantityTracked: boolean;
  isDepartmentTracked: boolean;
  isTaxAccount: boolean;
  isOffBalance: boolean;
  quickPick: string | null;
}

interface SeedFile {
  source: string;
  generatedAt: string;
  count: number;
  accounts: SeedAccount[];
}

export interface SeedChartResult {
  inserted: number;
  skipped: number;
  total: number;
}

/**
 * Bootstraps the per-org ChartOfAccount from the canonical 507-row NSBU
 * 1C "УЗ" export. Idempotent: rows that already exist for the org (matched
 * on `code`) are skipped, never overwritten. Mirrors the LocaleSeedService
 * "DB is authoritative after first bootstrap" pattern.
 *
 * The seed file lives at `src/ledger/seedChart/nsbu-chart-of-accounts.json`
 * and is regenerated by `tmp-convert-chart.js` from the analyst's
 * `Chart of accounts.xlsx`. Vid-distribution checks at generation time keep
 * the seed honest against the architecture-doc §4.3 reference counts.
 */
@Injectable()
export class ChartSeedService {
  private cache: SeedFile | null = null;

  constructor(
    @InjectModel(ChartOfAccount.name)
    private readonly chartModel: ChartOfAccountModel,
    private readonly logger: AppLoggerService,
  ) {}

  /**
   * Lazy-loaded canonical seed. Cached in memory since the JSON never
   * changes at runtime; service is a singleton per Nest container.
   */
  loadSeed(): SeedFile {
    if (this.cache) return this.cache;
    const filePath = path.join(SEED_DIR, SEED_FILE);
    const raw = fs.readFileSync(filePath, 'utf8');
    const parsed = JSON.parse(raw) as SeedFile;
    this.validateSeed(parsed);
    this.cache = parsed;
    return parsed;
  }

  /**
   * Bootstrap one org's chart from the canonical seed. Returns counts.
   * Service-layer guard: caller must ensure the actor has admin role on the
   * org — this method does NOT enforce authorization.
   */
  async seedForOrganization(
    organizationId: Types.ObjectId | string,
  ): Promise<SeedChartResult> {
    const orgId =
      typeof organizationId === 'string'
        ? new Types.ObjectId(organizationId)
        : organizationId;

    const seed = this.loadSeed();

    const existing = await this.chartModel
      .find({ organizationId: orgId })
      .select('code')
      .lean();
    const existingCodes = new Set(existing.map((d) => d.code));

    const toInsert = seed.accounts
      .filter((a) => !existingCodes.has(a.code))
      .map((a) => ({
        organizationId: orgId,
        code: a.code,
        name: a.name,
        subconto1Name: a.subconto1Name,
        subconto2Name: a.subconto2Name,
        subconto3Name: a.subconto3Name,
        vid: a.vid,
        isCurrencyTracked: a.isCurrencyTracked,
        isQuantityTracked: a.isQuantityTracked,
        isDepartmentTracked: a.isDepartmentTracked,
        isTaxAccount: a.isTaxAccount,
        isOffBalance: a.isOffBalance,
        quickPick: a.quickPick,
        isActive: true,
      }));

    if (toInsert.length === 0) {
      return { inserted: 0, skipped: existingCodes.size, total: seed.accounts.length };
    }

    try {
      await this.chartModel.insertMany(toInsert, { ordered: false });
    } catch (err) {
      // ordered:false continues past dup-key errors; only fully unexpected
      // bulk failures bubble up.
      const e = err as { code?: number; writeErrors?: unknown[] };
      if (e.code !== 11000 && e.writeErrors) {
        this.logger.error(
          new Error(`Chart seed insert had ${e.writeErrors.length} write errors`),
          { context: 'ChartSeedService.seedForOrganization', orgId: orgId.toString() },
        );
      }
    }

    this.logger.logAction('ledger.chart.seeded', {
      orgId: orgId.toString(),
      inserted: toInsert.length,
      skipped: existingCodes.size,
      total: seed.accounts.length,
    });

    return {
      inserted: toInsert.length,
      skipped: existingCodes.size,
      total: seed.accounts.length,
    };
  }

  private validateSeed(seed: SeedFile): void {
    if (!Array.isArray(seed.accounts) || seed.accounts.length === 0) {
      throw new Error('Seed file is missing accounts[]');
    }
    if (seed.count !== seed.accounts.length) {
      throw new Error(
        `Seed file count mismatch: header says ${seed.count}, accounts[] has ${seed.accounts.length}`,
      );
    }
    const seen = new Set<string>();
    for (const a of seed.accounts) {
      if (!a.code) throw new Error('Seed contains an account with no code');
      if (seen.has(a.code)) throw new Error(`Seed contains duplicate code: ${a.code}`);
      seen.add(a.code);
      if (!isAccountVid(a.vid)) {
        throw new Error(
          `Seed account ${a.code} has invalid vid "${a.vid}" — expected one of ${ALL_ACCOUNT_VIDS.join(', ')}`,
        );
      }
    }
  }
}
